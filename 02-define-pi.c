// ==================================================
// 【種類】確認（プリプロセスの結果を見る）
//
// 【目的】
//   #define は「決めた名前（PI）を、コンパイルの前に、決めた値（3.14）にそのまま置き換える」
//   命令であることを、自分の目で確かめる
//
// 【登場するファイル】
//   ・02-define-pi.c …… 材料（このファイル）。#define PI 3.14 と、PI を使った計算が書いてある
//   ・02-define-pi.i …… 結果（手順1で自分で作る）。PI を置き換えたあとの姿を保存したもの
//                         → 中身を見て確かめるためだけのファイル。編集しない
//
// 【手順】
//   1. gcc -E 02-define-pi.c -o 02-define-pi.i を実行する
//   2. tail -n 6 02-define-pi.i を実行する（最後の6行だけを画面に表示する）
//   3. printf の行で、PI と書いたところが 3.14 に変わっていることを確かめる
//        ・#define の行そのものは、結果には残っていない（置き換えが終わったら消える）
//   4. gcc 02-define-pi.c -o 02-define-pi を実行する（-E を付けないので、4つの工程を最後まで実行して、実行ファイルを作る）
//   5. ./02-define-pi を実行し、「円の面積は12.560000です。」と表示されることを確かめる
//
// 【確認できたらOK】
//   ・手順3で、PI が 3.14 に置き換わっていた
//   ・手順5で、「円の面積は12.560000です。」と表示された
//
// 【やってみよう】
//   ① #define PI 3.14 を #define PI 3.14159 に変えて、手順4〜5をもう一度実行する。
//      #define の1行を変えるだけで、PI を使っているところがすべて変わる
//   ② #define PI 3.14; のように最後に ; を付けて、手順4を実行する。エラーになる理由を、手順1〜2で確かめる
//
// 【おまけ】#define PI 3 にすると、警告（warning）が出るのはなぜ？
//   ・試し方：#define PI 3.14 を #define PI 3 に変えて、手順4〜5を実行する
//   ・こんな警告が出る：
//       warning: format specifies type 'double' but the argument has type 'int'
//       （%f は小数（double）を表示する指定なのに、整数（int）が渡されている、という意味）
//   ・理由：#define は文字を置き換えるだけなので、r * r * PI は r * r * 3 になる。
//           r も 3 も整数なので、整数同士のかけ算になり、答えも整数（int）になる
//           → 後期第4回（キャスト）の 7 / 2 が 3 になったのと同じ考え方
//
//   ・対応表（r は int の 2）
//     | #define の書き方 | 置き換えたあとの式 | 計算の種類     | 答えの型 | %f で表示すると            |
//     |-----------------|--------------------|----------------|----------|----------------------------|
//     | #define PI 3.14 | r * r * 3.14       | 整数 × 小数    | double   | 12.560000（OK）            |
//     | #define PI 3    | r * r * 3          | 整数 × 整数    | int      | 警告。おかしな値になる     |
//     | #define PI 3.0  | r * r * 3.0        | 整数 × 小数    | double   | 12.000000（OK）            |
//
//   ・警告を消す方法（どちらか）
//       ① #define PI 3.0 にする（.0 を付けると、C言語は小数として扱う。%f のままでOK）
//       ② printf の %f を %d に変える（整数を表示する指定に合わせる）
//   ・警告はエラーとちがって実行ファイルはできるが、表示がおかしくなる（このMacでは 0.000000 になった）。
//     警告が出たら無視しないこと
//
// 【回答・確認結果】
//   ① PI を 3.14159 にすると、r * r * 3.14159 に展開され、12.566360 と表示された。
//   ② PI を 3.14; にすると、printf の引数が r * r * 3.14; となる。
//   引数内のセミコロンが原因で「expected ')' before ';' token」とエラーになった。
//   おまけ：PI を 3 にすると式は int になり、double を要求する %f と合わず警告が出た。
//   この場合の実行結果は未定義。PI を 3.0 にするか、表示指定を %d にする。
// ==================================================
#include <stdio.h>
#define PI 3.14159

int main(void)
{
    int r = 2;
    printf("円の面積は%fです。\n", r * r * PI);
    return 0;
}
